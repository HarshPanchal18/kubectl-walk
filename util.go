// Resolve kubernetes resource identifier
func resolveKind(input string) string {
	switch input {
    case "po", "pod", "pods":
        return "pod"
    case "svc", "service", "services":
        return "service"
    case "cm", "configmap", "configmaps":
        return "configmap"
    case "secret", "secrets":
        return "secret"
    case "ns", "namespace", "namespaces":
        return "namespace"
    case "no", "node", "nodes":
        return "node"
    case "ev", "event", "events":
        return "event"
    case "sa", "serviceaccount", "serviceaccounts":
        return "serviceaccount"
    case "ep", "endpoints":
        return "endpoints"
    case "sc", "storageclass", "storageclasses":
        return "storageclass"
    case "pv", "persistentvolume", "persistentvolumes":
        return "persistentvolume"
    case "pvc", "persistentvolumeclaim", "persistentvolumeclaims":
        return "persistentvolumeclaim"

	case "deploy", "deployment", "deployments":
		return "deployment"
	case "sts", "statefulset", "statefulsets":
		return "statefulset"
    case "ds", "daemonset", "daemonsets":
        return "daemonset"
    case "rs", "replicaset", "replicasets":
        return "replicaset"

	case "job", "jobs":
		return "job"
	case "cj", "cronjob", "cronjobs":
		return "cronjob"

	case "ing", "ingress", "ingresses":
		return "ingress"
	case "netpol", "networkpolicy", "networkpolicies":
		return "networkpolicy"

	case "eplice", "endpointsslice", "endpointslices":
		return "endpointsslice"

    case "role", "roles":
        return "role"
    case "rb", "rolebinding", "rolebindings":
        return "rolebinding"
    case "cr", "clusterrole", "clusterroles":
        return "clusterrole"
    case "crb", "clusterrolebinding", "clusterrolebindings":
        return "clusterrolebinding"

    case "hpa", "horizontalpodautoscaler", "horizontalpodautoscalers":
        return "horizontalpodautoscaler"

	default:
		return input
	}
}

